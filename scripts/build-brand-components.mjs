/*
  Turns the traced logo SVGs in /assets into one React module.
  Re-run scripts/trace-logos.py then this script if the artwork is reissued.
*/
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const ASSETS = path.join(process.cwd(), 'assets')

function read(name) {
  const svg = readFileSync(path.join(ASSETS, `${name}.svg`), 'utf8')
  return {
    viewBox: svg.match(/viewBox="([^"]+)"/)[1],
    inner: svg.slice(svg.indexOf('>') + 1, svg.lastIndexOf('</svg>')).replace(/\s+/g, ' ').trim(),
  }
}

const marks = { LogoHorizontal: 'horizontal', Monogram: 'monogram' }

let out = `/*
  Brand marks, traced from the supplied Pow & Partners artwork.
  Generated by scripts/build-brand-components.mjs. Do not edit by hand.

  Ink is drawn with currentColor, so one component serves the black and the
  white lockups: set the colour on the parent and the mark follows.
*/

type MarkProps = {
  className?: string
  /** Set when the mark is the only thing naming the studio, as in the header. */
  label?: string
}

`

for (const [component, file] of Object.entries(marks)) {
  const { viewBox, inner } = read(file)
  out += `export function ${component}({ className, label }: MarkProps) {
  return (
    <svg
      viewBox="${viewBox}"
      className={className}
      xmlns="http://www.w3.org/2000/svg"
      {...(label ? { role: 'img', 'aria-label': label } : { 'aria-hidden': true, focusable: false })}
    >
      ${inner}
    </svg>
  )
}

`
}

out += `/*
  The connector. The plan is explicit that the ampersand is the brand, so it is
  set in the display face rather than drawn, and sits inline at the text size.
*/
export function Amp({ className = '' }: { className?: string }) {
  return (
    <span aria-hidden="true" className={\`font-display not-italic \${className}\`}>
      &amp;
    </span>
  )
}
`

writeFileSync(path.join(process.cwd(), 'components/Brand.tsx'), out)
console.log('components/Brand.tsx written,', (out.length / 1024).toFixed(0) + 'kb')
